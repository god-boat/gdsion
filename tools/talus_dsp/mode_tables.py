"""Writes a generated mode-table header under gdsion/src/dsp/.

A table is a constexpr array of sion::dsp::ModeShape (dsp/modal_bank.h): each
mode's ratio to the fundamental, and its strike weights from the center of the
resonator to its edge. gen_membrane_modes.py and gen_bar_modes.py compute the
tables; the channel and model.py read them.
"""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
DSP = ROOT / "src" / "dsp"
POSITION_POINTS = int(re.search(r"constexpr int MODE_POSITION_POINTS = (\d+);", (DSP / "modal_bank.h").read_text(encoding="utf-8")).group(1))

_NOTICE = [
	"/***************************************************/",
	"/* Part of GDSiON software synthesizer             */",
	"/* Copyright (c) 2024 Yuri Sizov and contributors  */",
	"/* Provided under MIT                              */",
	"/***************************************************/",
	"",
]


class Table:
	def __init__(self, name: str, comment: list[str], modes: list[tuple[float, list[float], str]]):
		"""modes: (ratio, weights, a note printed after the row)."""
		self.name = name
		self.comment = comment
		self.modes = modes


def write_header(filename: str, generator: str, count_name: str, tables: list[Table]) -> None:
	guard = "SION_DSP_" + filename.upper().replace(".", "_")
	count = len(tables[0].modes)
	lines = _NOTICE + [
		f"// Generated by tools/talus_dsp/{generator}. Do not edit.",
		"",
		f"#ifndef {guard}",
		f"#define {guard}",
		"",
		'#include "dsp/modal_bank.h"',
		"",
		"namespace sion::dsp {",
		"",
		f"constexpr int {count_name} = {count};",
	]
	for table in tables:
		assert len(table.modes) == count
		lines += [""] + [f"// {line}" if line else "//" for line in table.comment]
		lines.append(f"inline constexpr ModeShape {table.name}[{count_name}] = {{")
		for ratio, weights, note in table.modes:
			assert len(weights) == POSITION_POINTS
			text = ", ".join(f"{round(w, 9) + 0.0:.9f}" for w in weights)
			lines.append(f"\t{{ {ratio:.9f}, {{ {text} }} }}, // {note}")
		lines.append("};")
	lines += ["", "} // namespace sion::dsp", "", f"#endif // {guard}", ""]
	path = DSP / filename
	path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
	print(f"Wrote {path.relative_to(ROOT)}: {', '.join(f'{t.name} ratio 1 to {t.modes[-1][0]:.3f}' for t in tables)} ({count} modes)")


def read_tables(filename: str) -> dict[str, list[tuple[float, list[float]]]]:
	"""Every table in a generated header, as (ratio, weights) rows by table name."""
	text = (DSP / filename).read_text(encoding="utf-8")
	tables = {}
	for name, body in re.findall(r"ModeShape (\w+)\[\w+\] = \{\n(.*?)\n\};", text, re.S):
		tables[name] = [(float(ratio), [float(w) for w in weights.split(",")]) for ratio, weights in re.findall(r"\{ ([0-9.]+), \{ ([^}]*) \} \}", body)]
	return tables
